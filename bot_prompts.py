def questions_prompt(goal: str) -> str:
    return f"""Ты — эксперт по диагностике уровня знаний. Сгенерируй РОВНО 4 вопроса для оценки уровня пользователя по теме: "{goal}".

Пользователь будет отвечать на каждый вопрос по фиксированной шкале:
A) Никогда не пробовал / не слышал
B) Знаком в теории, но не практиковал
C) Практиковал, есть реальный опыт
D) Занимаюсь на продвинутом/профессиональном уровне

Формулируй вопросы так, чтобы ответ по этой шкале был естественным.
Используй форму "Насколько ты знаком с...", "Как часто ты...", "В какой мере ты практиковал...".
НЕ используй форму "Что такое...", "Какой...", "Сколько стоит...".

Верни ТОЛЬКО валидный JSON без какого-либо текста до или после. Формат строго такой:
[
  {{"question": "Текст вопроса"}},
  {{"question": "Текст вопроса"}},
  {{"question": "Текст вопроса"}},
  {{"question": "Текст вопроса"}}
]"""


def track_prompt(goal: str, level: str, hours: int, months: int, weeks: int, qa_text: str) -> str:
    return f"""Ты — персональный ИИ-навигатор по обучению. Составь детальный трек обучения.

ПРОФИЛЬ ПОЛЬЗОВАТЕЛЯ:
- Цель: {goal}
- Уровень: {level}
- Время: {hours} ч/нед · {months} мес ({weeks} нед)

Ответы диагностики:
{qa_text}

A/B → пробел в знаниях, включи в трек с нуля. C/D → уже владеет, только углубляй.

ТРЕБОВАНИЯ К МАТЕРИАЛАМ (строго):
- Только БЕСПЛАТНЫЕ материалы
- Только русский язык (написаны или озвучены на русском)
- Допустимые источники: YouTube, Stepik (бесплатные курсы), Habr, Rutube, VK Видео, открытая документация, GitHub
- ЗАПРЕЩЕНО упоминать: Coursera, Udemy, Skillbox, GeekBrains, Яндекс Практикум — они платные
- Указывай КОНКРЕТНЫЕ названия каналов, курсов, плейлистов или статей

Составь трек строго в формате:

## 📍 Этап 1: [Название]
**Длительность:** X недель
**Что изучать:** Конкретные понятия и техники — не общие категории. Примеры: Python — «f-strings, list comprehension, dict.get()»; английский — «Present Perfect vs Past Simple, фразовые глаголы go on / give up».
**Материалы:**
- [YouTube] Название видео или плейлиста — Название канала
- [Stepik] Название курса (бесплатно)
- [Habr] Название статьи или подборки
**Результат:** что конкретно умеет делать пользователь после этапа

## 📍 Этап 2: [Название]
...

## 🎯 Итог
Карьерные перспективы после прохождения трека (2–3 предложения).

Ориентируйся на {weeks} недель (±20%). Тон: простой и ободряющий для новичка, лаконичный для продвинутого."""


def simplify_prompt(goal: str, level: str, stage_title: str, stage_content: str) -> str:
    return f"""Пользователь изучает «{goal}» (уровень: {level}).

Этап «{stage_title}» оказался слишком сложным:
{stage_content[:600]}

Перепиши содержимое этапа проще: начни с самых базовых шагов, добавь больше объяснений.
Также предложи 2-3 более простых бесплатных русскоязычных материала (YouTube, Stepik, Habr).
Ответь просто текстом без markdown-заголовков."""


def alternative_prompt(goal: str, level: str, stage_title: str, stage_content: str) -> str:
    return f"""Пользователь изучает «{goal}» (уровень: {level}).

Для этапа «{stage_title}» нужны альтернативные бесплатные материалы на русском языке.
Содержание этапа: {stage_content[:400]}

Предложи 3-5 конкретных бесплатных русскоязычных материалов:
- YouTube каналы или конкретные плейлисты
- Бесплатные курсы на Stepik
- Статьи или подборки на Habr

Формат каждой строки: [Источник] Конкретное название — краткое описание"""
